/**
 * Writes `src/icon/phosphor-markup.ts` from the official Phosphor SVGs (`@phosphor-icons/core`): only
 * the icons the template names, in the weights it offers, as the markup inside each `<svg>`. Run it
 * after adding a name to `icons` (`pnpm --filter @repo/ui icons`). Nothing of Phosphor ships but these.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** The template's name for an icon (what it means) and Phosphor's. */
const icons = {
  back: 'arrow-left',
  check: 'check',
  close: 'x',
  customers: 'address-book',
  error: 'warning-circle',
  expand: 'caret-up-down',
  folder: 'folder',
  globe: 'globe',
  help: 'question',
  home: 'house',
  info: 'info',
  key: 'key',
  list: 'list-bullets',
  mail: 'envelope-simple',
  menu: 'list',
  monitor: 'monitor',
  moon: 'moon',
  next: 'caret-right',
  organization: 'buildings',
  phone: 'device-mobile',
  plus: 'plus',
  preferences: 'sliders-horizontal',
  profile: 'user',
  role: 'identification-badge',
  search: 'magnifying-glass',
  security: 'shield',
  'sign-out': 'sign-out',
  success: 'check-circle',
  sun: 'sun',
  users: 'users',
  warning: 'warning'
}

/**
 * The weights each icon comes in. Every icon has `regular`, the weight the template draws by default;
 * the others only for the icons listed, so nothing ships that is not drawn. The side menu's icons
 * also come in `duotone`, to mark the current screen.
 */
const weights = {
  regular: Object.keys(icons),
  duotone: ['home', 'profile', 'security', 'preferences', 'monitor', 'organization', 'users', 'role', 'customers']
}

// The package keeps its SVGs in `assets/`, which it does not export: read them from where it is installed.
const assets = fileURLToPath(new URL('../node_modules/@phosphor-icons/core/assets', import.meta.url))

/** The markup inside the `<svg>`: Phosphor draws on a 256 grid, filled with the current colour. */
const markup = (weight, name) => {
  const file = join(assets, weight, `${name}${weight === 'regular' ? '' : `-${weight}`}.svg`)
  return readFileSync(file, 'utf8')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .trim()
}

const body = Object.entries(weights)
  .map(
    ([weight, names]) =>
      `  ${weight}: {\n${names.map((name) => `    '${name}': '${markup(weight, icons[name])}'`).join(',\n')}\n  }`
  )
  .join(',\n')

writeFileSync(
  new URL('../src/icon/phosphor-markup.ts', import.meta.url),
  `// Generated by scripts/generate-icons.mjs from @phosphor-icons/core: do not edit by hand.\nexport const phosphorMarkup = {\n${body}\n} as const\n`
)
console.log(
  Object.entries(weights)
    .map(([weight, names]) => `${names.length} in ${weight}`)
    .join(', ')
)
